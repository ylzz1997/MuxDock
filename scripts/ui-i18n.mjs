import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

export async function checkI18n({ frame, page, cli, until, delay, updateSettings, resizePanel, command, editor }) {
  const locales = ['en', 'zh-cn', 'zh-tw', 'ja', 'ko', 'de', 'fr', 'es', 'pt-br', 'ru'];
  const catalogs = Object.fromEntries(await Promise.all(locales.map(async locale => [locale, JSON.parse(await readFile(`l10n/${locale}.json`, 'utf8'))])));
  const checks = [];
  await resizePanel(420);
  await frame.getByRole('treeitem', { name: 'my-project', exact: true }).click();
  await frame.locator('.connection-status.connected').waitFor();
  const tabKey = await frame.locator('.terminal-tab[aria-selected="true"]').getAttribute('data-key');
  const clients = () => cli(['list-clients', '-t', 'my-project', '-F', '#{client_pid}']).trim();
  const originalClients = await until(async () => clients());
  assert.ok(originalClients);
  cli(['send-keys', '-t', 'my-project', "printf 'I18N_%s\\n' 'MARKER'", 'Enter']);
  await until(async () => (await frame.locator('.terminal-instance:not([hidden]) .xterm-rows').textContent()).includes('I18N_MARKER'));
  await frame.getByRole('button', { name: catalogs['zh-cn'].searchTerminal, exact: true }).click();
  await frame.locator('.search-input').fill('I18N_MARKER');
  await until(async () => Number(await frame.locator('.search-bar').getAttribute('data-result-count')) >= 1);
  if (await frame.locator('.search-caseSensitive').getAttribute('aria-pressed') !== 'true') await frame.locator('.search-caseSensitive').click();
  const searchCount = await frame.locator('.search-bar').getAttribute('data-result-count');
  await frame.getByRole('button', { name: catalogs['zh-cn'].filterSessions, exact: true }).click();
  await frame.locator('.filter').fill('my-project');
  await frame.getByRole('button', { name: catalogs['zh-cn'].collapseSidebar, exact: true }).click();
  await updateSettings({ 'muxdock.language': 'en' });
  await until(async () => await frame.locator('html').getAttribute('lang') === 'en');
  assert.equal(await frame.locator('.sidebar').isVisible(), false);
  assert.equal(await frame.locator('.filter').inputValue(), 'my-project');
  await frame.getByRole('button', { name: catalogs.en.expandSidebar, exact: true }).click();
  checks.push('live language change preserves collapsed sidebar, filter and active terminal');
  await frame.getByRole('treeitem', { name: 'my-project', exact: true }).click({ button: 'right' });
  await frame.getByRole('menuitem', { name: catalogs.en.sessionDetails, exact: true }).click();
  await until(async () => (await frame.locator('.details-body dt').count()) > 0);
  for (const locale of locales) {
    const messages = catalogs[locale];
    await updateSettings({ 'muxdock.language': locale });
    await until(async () => await frame.locator('html').getAttribute('lang') === locale && await frame.locator('.details-body dt').first().textContent() === messages.manager);
    assert.equal(await frame.locator('.sidebar-title').textContent(), messages.sessions, locale);
    assert.equal(await frame.locator('.welcome h1').textContent(), messages.chooseSession, locale);
    assert.equal(await frame.locator('.new-session').textContent(), messages.newSession, locale);
    assert.equal(await frame.locator('.connection-status').textContent(), messages.connected, locale);
    assert.equal(await frame.locator('.search-input').getAttribute('aria-label'), messages.searchContent, locale);
    assert.equal(await frame.locator('.search-input').inputValue(), 'I18N_MARKER');
    assert.equal(await frame.locator('.search-caseSensitive').getAttribute('aria-pressed'), 'true');
    assert.equal(await frame.locator('.search-bar').getAttribute('data-result-count'), searchCount);
    assert.equal(await frame.locator('.session-details h2').textContent(), messages.sessionDetails);
    assert.equal(await frame.getByRole('button', { name: messages.copyDetails, exact: true }).count(), 1);
    assert.ok((await frame.locator('.details-body dd').allTextContents()).includes('my-project'));
    assert.ok(!(await frame.locator('.details-body dd').allTextContents()).some(value => /^\d{4}-\d\d-\d\dT/.test(value)), 'timestamps are formatted for locale');
    assert.equal(await frame.locator('.terminal-tab[aria-selected="true"]').getAttribute('data-key'), tabKey);
    assert.equal(clients(), originalClients, `${locale}: no reconnect`);
    await frame.locator('.session-details').screenshot({ path: `.test-results/i18n-${editor}-${locale}-details.png` });
    checks.push(`${locale}: translated live panel, search, details, date and accessibility labels; same backend client`);
  }
  await frame.getByRole('button', { name: catalogs.ru.closeDetails, exact: true }).click();
  await frame.getByRole('button', { name: catalogs.ru.closeSearch, exact: true }).click();
  await frame.getByRole('button', { name: catalogs.ru.moreActions, exact: true }).click();
  await frame.getByRole('menuitem', { name: catalogs.ru.language, exact: true }).click();
  const quick = page.locator('.quick-input-widget');
  await quick.waitFor({ state: 'visible' });
  assert.ok((await quick.textContent()).includes(catalogs.ru.languagePrompt));
  await quick.locator('input[type="text"]').fill('Deutsch');
  await page.keyboard.press('Enter');
  await quick.waitFor({ state: 'hidden' });
  await until(async () => await frame.locator('html').getAttribute('lang') === 'de');
  checks.push('language picker is discoverable in More actions and changes the persisted setting');
  await frame.getByRole('treeitem', { name: 'my-project', exact: true }).click({ button: 'right' });
  await frame.getByRole('menuitem', { name: catalogs.de.killSessionMenu, exact: true }).click();
  const dialog = page.locator('.monaco-dialog-box');
  await dialog.waitFor({ state: 'visible' });
  assert.ok((await dialog.textContent()).includes(catalogs.de.confirmKill.replace('{name}', 'my-project')));
  await dialog.getByRole('button', { name: /Cancel|Abbrechen|取消/ }).click();
  cli(['has-session', '-t', 'my-project']); assert.equal(clients(), originalClients);
  checks.push('native destructive confirmation is translated and Cancel preserves the session');
  // Long labels must remain usable in the existing narrow sidebar.
  await frame.getByRole('button', { name: catalogs.de.moreActions, exact: true }).click();
  await frame.getByRole('menuitem', { name: catalogs.de.batchActions, exact: true }).click();
  await frame.locator('.session-checkbox').first().check();
  for (const locale of ['de', 'fr', 'ru', 'ja']) {
    await updateSettings({ 'muxdock.language': locale });
    await until(async () => await frame.locator('html').getAttribute('lang') === locale);
    await frame.locator('.splitter').focus();
    for (let i = 0; i < 8; i++) await page.keyboard.press('ArrowRight');
    assert.equal(await frame.locator('.session-checkbox').first().isChecked(), true);
    const bounds = await frame.locator('.batch-toolbar').evaluate(element => ({ width: element.clientWidth, scroll: element.scrollWidth, buttons: [...element.querySelectorAll('.batch-button')].map(button => ({ width: button.clientWidth, scroll: button.scrollWidth })) }));
    assert.ok(bounds.scroll <= bounds.width + 1, `${locale} toolbar overflow: ${JSON.stringify(bounds)}`);
    assert.ok(bounds.buttons.every(button => button.scroll <= button.width + 1), `${locale} button overflow`);
    await frame.locator('.dock').screenshot({ path: `.test-results/i18n-${editor}-${locale}-panel.png` });
  }
  checks.push('batch selection survives switching languages; long labels fit narrow panels');
  await frame.getByRole('button', { name: catalogs.ja.exitBatch, exact: true }).click();
  await updateSettings({ 'muxdock.language': 'auto' });
  await until(async () => await frame.locator('html').getAttribute('lang') === 'en');
  assert.equal(await frame.locator('.sidebar-title').textContent(), catalogs.en.sessions);
  checks.push('auto follows the English editor language');
  await updateSettings({ 'muxdock.language': 'unsupported-language' });
  await until(async () => await frame.locator('html').getAttribute('lang') === 'en');
  await delay(500); assert.equal(await frame.locator('.sidebar-title').textContent(), catalogs.en.sessions);
  await updateSettings({ 'muxdock.language': 'fr' });
  await until(async () => await frame.locator('html').getAttribute('lang') === 'fr');
  await command('Developer: Reload Webviews');
  const restored = await until(async () => {
    for (const candidate of page.frames()) if (candidate !== frame && await candidate.locator('.dock').count().catch(() => 0)) return candidate;
    return false;
  });
  await until(async () => await restored.locator('.connection-status').textContent() === catalogs.fr.connected);
  assert.equal(await restored.locator('html').getAttribute('lang'), 'fr');
  assert.equal(await restored.locator('.filter').inputValue(), 'my-project');
  assert.equal(clients(), originalClients);
  assert.ok((await restored.locator('.terminal-instance:not([hidden]) .xterm-rows').textContent()).includes('I18N_MARKER'));
  const input = restored.locator('.terminal-instance:not([hidden]) .xterm-helper-textarea');
  await input.focus(); await page.keyboard.press('Control+u'); await page.keyboard.type("printf 'I18N_INPUT_%s\\n' 'OK'"); await page.keyboard.press('Enter');
  await until(async () => cli(['capture-pane', '-p', '-t', 'my-project']).includes('I18N_INPUT_OK'));
  checks.push('fallback, persisted locale and webview reload preserve terminal history, client and usable input');
  return checks;
}
