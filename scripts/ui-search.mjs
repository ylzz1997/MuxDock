import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';

export async function checkTerminalSearch({ frame, page, cli, until, delay, resizePanel }) {
  const fixture = path.resolve('.test-results/search-output.py');
  const output = 'FIND_DOCK_ALPHA\nfind_dock_alpha\nFIND_DOCK_ALPHABET\nFIND_DOCK_ALPHA\none FIND_DOCK_ALPHA two\nFIND_DOCK_SEARCH_READY\n';
  await writeFile(fixture, `import sys\nsys.stdout.write(${JSON.stringify(output)})\nsys.stdout.flush()\n`);
  const quote = value => `'${value.replaceAll("'", "'\\''")}'`;
  cli(['send-keys', '-t', 'my-project:logs', '-l', `python3 ${quote(fixture)}`]); cli(['send-keys', '-t', 'my-project:logs', 'Enter']);
  await until(async () => (await frame.locator('.terminal-instance:not([hidden]) .xterm-rows').textContent()).includes('FIND_DOCK_SEARCH_READY'));
  const screen = frame.locator('.terminal-instance:not([hidden]) .xterm-screen');
  await screen.click();
  const before = await screen.boundingBox();
  await page.keyboard.press('Meta+f');
  const widget = frame.getByRole('search', { name: '终端搜索', exact: true });
  await widget.waitFor({ state: 'visible' });
  const input = widget.getByRole('textbox', { name: '搜索终端内容', exact: true });
  const count = async expected => { await until(async () => Number(await widget.getAttribute('data-result-count')) === expected); };
  const index = () => widget.getAttribute('data-result-index').then(Number);
  const option = name => widget.getByRole('button', { name, exact: true });
  for (const name of ['区分大小写', '全词匹配', '使用正则表达式']) if (await option(name).getAttribute('aria-pressed') === 'true') await option(name).click();
  await input.fill('find_dock_alpha'); await count(5);
  assert.equal((await screen.boundingBox()).height, before.height, 'Floating search must not resize the terminal');
  await until(async () => await frame.locator('.terminal-instance:not([hidden]) .xterm-find-result-decoration').count() >= 5);
  await frame.locator('.dock').screenshot({ path: '.test-results/muxdock-search.png' });
  await widget.screenshot({ path: '.test-results/muxdock-find-widget.png' });
  const first = await index();
  await widget.getByRole('button', { name: '下一个匹配项', exact: true }).click();
  assert.equal(await index(), (first + 1) % 5);
  assert.ok(await input.evaluate(element => document.activeElement === element));
  await input.press('Shift+Enter'); assert.equal(await index(), first);
  for (let i = 0; i < 5; i++) await input.press('Enter');
  assert.equal(await index(), first, 'Next wraps through all results');
  await input.press('F3'); assert.equal(await index(), (first + 1) % 5);
  const checks = ['floating find widget preserves terminal size, highlights all matches, counts results and wraps with buttons/Enter/F3'];
  await option('全词匹配').click(); await count(4);
  await option('区分大小写').click(); await count(1);
  await input.fill('FIND_DOCK_ALPHA'); await count(3);
  checks.push('case sensitivity and whole-word matching change the actual result set');
  await option('使用正则表达式').click();
  await input.fill('FIND_DOCK_ALPHA$'); await count(2);
  await input.fill('[');
  assert.equal(await input.getAttribute('aria-invalid'), 'true');
  assert.ok((await widget.getByRole('alert').textContent()).includes('正则表达式无效'));
  assert.ok(await widget.getByRole('button', { name: '下一个匹配项', exact: true }).isDisabled());
  await input.fill('FIND_DOCK_ALPHA$'); await count(2);
  assert.equal(await input.getAttribute('aria-invalid'), null);
  checks.push('regex search validates errors, disables navigation and recovers without breaking the terminal');
  await input.press('Alt+r'); assert.equal(await option('使用正则表达式').getAttribute('aria-pressed'), 'false');
  await input.fill('no_match_for_this_query'); await count(0);
  assert.equal(await widget.locator('.search-count').textContent(), '无结果');
  await input.fill(''); assert.equal(await widget.locator('.search-count').textContent(), '');
  assert.equal(await frame.locator('.terminal-instance:not([hidden]) .xterm-find-result-decoration').count(), 0);
  await input.fill('FIND_DOCK_ALPHA'); await count(3);
  cli(['send-keys', '-t', 'my-project:logs', '-l', `python3 -c ${quote("print('FIND_DOCK_' + 'ALPHA')")}`]); cli(['send-keys', '-t', 'my-project:logs', 'Enter']);
  await count(4);
  checks.push('empty/no-result queries clear highlights and incoming output updates the result count');
  cli(['new-session', '-d', '-s', 'search-other', '/bin/sh']);
  await frame.getByRole('button', { name: '刷新', exact: true }).click();
  await frame.getByRole('treeitem', { name: 'search-other', exact: true }).click();
  await until(async () => await frame.getByRole('tab', { name: 'search-other (tmux)', exact: true }).getAttribute('aria-selected') === 'true');
  await count(0);
  assert.equal(await input.inputValue(), 'FIND_DOCK_ALPHA');
  await frame.getByRole('tab', { name: 'my-project (tmux)', exact: true }).click(); await count(4);
  await frame.getByRole('button', { name: '关闭标签页 search-other (tmux)', exact: true }).click(); cli(['kill-session', '-t', 'search-other']);
  checks.push('changing terminal tabs searches the active buffer while retaining the query/options');
  for (const height of [220, 120]) {
    await resizePanel(height);
    const layout = await widget.evaluate(element => {
      const box = element.getBoundingClientRect(); const content = document.querySelector('.terminal-content').getBoundingClientRect();
      const close = element.querySelector('.search-close').getBoundingClientRect();
      return { top: box.top, bottom: box.bottom, left: box.left, right: box.right, buttonBottom: close.bottom, parent: { top: content.top, bottom: content.bottom, left: content.left, right: content.right } };
    });
    assert.ok(layout.top >= layout.parent.top && layout.bottom <= layout.parent.bottom + 1 && layout.left >= layout.parent.left && layout.right <= layout.parent.right + 1, 'Search remains inside a short terminal panel');
    assert.ok(layout.buttonBottom <= layout.parent.bottom + 1, 'Search navigation and close controls remain fully visible in a short panel');
    if (height === 120) await frame.locator('.dock').screenshot({ path: '.test-results/muxdock-search-compact.png' });
  }
  await resizePanel(350);
  await input.focus(); await input.press('Escape');
  assert.equal(await widget.isVisible(), false);
  assert.ok(await frame.locator('.terminal-instance:not([hidden]) .xterm-helper-textarea').evaluate(element => document.activeElement === element));
  await page.keyboard.press('Meta+f');
  assert.equal(await input.inputValue(), 'FIND_DOCK_ALPHA');
  for (const name of ['区分大小写', '全词匹配', '使用正则表达式']) if (await option(name).getAttribute('aria-pressed') === 'true') await option(name).click();
  await input.fill(''); await input.press('Escape'); await delay(100);
  checks.push('find stays inside compact panels; Escape restores terminal input and reopening retains the query');
  return checks;
}
